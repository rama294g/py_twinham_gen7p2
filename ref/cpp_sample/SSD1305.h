  char reverseBits(char c) {
    char reversed = 0;
    for (int i = 0; i < 8; i++) {
      reversed = (reversed << 1) | (c & 1);
      c >>= 1;
    }
    return reversed;
  }

  // Update the display with the current buffer contents
  int updateDisplayAll() {
    const uint32_t delay = 2;
    int ret;
    while (true) {
      ret = display_off();
      thread_sleep_for(delay);
      if (ret == 0)
        break;
    }
    for (char page = 0; page < 4; page++) {
      moveBuffer(page);
      ret = changeDisplay(page);
      if (ret)
        return 1;
      ret = sendBuffer();
      if (ret)
        return 1;
      thread_sleep_for(delay);
    }
    while (true) {
      ret = display_on();
      thread_sleep_for(delay);
      if (ret == 0)
        break;
    }
    return 0;
  }
  int changeDisplay(const char _page) {
    const char page = 3 - _page;
    int ret;
    while (true) {
      ret = sendCommand(SSD1305_PAGEADDR | page); // Set page address
      if (ret == 0)
        break;
      thread_sleep_for(1);
    }
    while (true) {
      ret = sendCommand(SSD1305_COLUMNADDR_L); // Set column address to 0
      if (ret == 0)
        break;
      thread_sleep_for(1);
    }
    while (true) {
      ret = sendCommand(SSD1305_COLUMNADDR_H); // Set column address to 0
      if (ret == 0)
        break;
      thread_sleep_for(1);
    }
    return 0;
  }
  void setBuffer(const int _pos, const char *_v, const int _len) {
    memcpy(buffer + _pos, _v, _len);
  }
  void moveBuffer(const char _page) {
    for (int j = 0; j < SCREEN_WIDTH; j++) {
      sending_buffer[SCREEN_WIDTH - 1 - j] =
          reverseBits(buffer[(int)_page * SCREEN_WIDTH + j]);
    }
  }
  int sendBuffer() {
    m_i2c.start();
    while (true) {
      if (m_i2c.write(m_8bit_addr) == 1)
        break;
      thread_sleep_for(1);
    }
    while (true) {
      if (m_i2c.write(0x40) == 1)
        break;
      thread_sleep_for(1);
    }
    for (int i = 0; i < SCREEN_WIDTH; i++) {
      while (true) {
        if (m_i2c.write(sending_buffer[i]) == 1)
          break;
        thread_sleep_for(1);
      }
    }
    m_i2c.stop();
    return 0;
  }
  int sendBuffer2() {
    const int packet_div = 16;
    int ret;
    for (int i = 0; i < SCREEN_WIDTH; i += packet_div) {
      while (true) {
        ret = sendData(sending_buffer + i, packet_div);
        if (!ret)
          break;
        thread_sleep_for(1);
      }
    }
    return 0;
  }

  // Set a pixel on the display
  void setPixel(char x, char y, bool color) {
    if (x >= SCREEN_WIDTH || y >= SCREEN_HEIGHT)
      return; // Out of bounds

    static const char one = 1;
    if (color) {
      buffer[(y / 8) * SCREEN_WIDTH + x] |= (one << (y % 8)); // Set pixel
    } else {
      buffer[(y / 8) * SCREEN_WIDTH + x] &= ~(one << (y % 8)); // Clear pixel
    }
  }
  void setChar(const int x, const int y, const char code,
               const bool _negative) {
    if (code < 32)
      return;
    if (code >= 98 + 32)
      return;
    char buf[8];
    memcpy(buf, font_8x8[code - 32], 8);
    if (_negative) {
      for (int i = 0; i < 8; i++)
        buf[i] = ~buf[i];
    }
    memcpy(buffer + y * SCREEN_WIDTH + x, buf, 8);
  }
  void setString(const int x, const int y, const char *_str, const int _str_len,
                 const bool _negative) {
    for (int i = 0; i < _str_len; i++) {
      if (_str[i] == 0)
        break;
      setChar(x + i * 8, y, _str[i], _negative);
    }
  }

  // Draw a line using Bresenham's algorithm
  void drawLine(char x1, char y1, char x2, char y2, bool color) {
    int dx = abs(x2 - x1);
    int dy = abs(y2 - y1);
    int sx = (x1 < x2) ? 1 : -1;
    int sy = (y1 < y2) ? 1 : -1;
    int err = dx - dy;

    while (true) {
      setPixel(x1, y1, color);

      if (x1 == x2 && y1 == y2)
        break;

      int e2 = err * 2;
      if (e2 > -dy) {
        err -= dy;
        x1 += sx;
      }
      if (e2 < dx) {
        err += dx;
        y1 += sy;
      }
    }
  }
