  int sendData(const char data) {
    static char com[2];
    com[0] = 0x40;
    com[1] = data;
    int ret = m_i2c.write(m_8bit_addr, com, sizeof(com), false);
    if (ret) {
      unsigned char buf[] = "send data1 error\r\n";
      m_uart.add_uart_data(buf, sizeof(buf));
    }
    return ret;
  }
  int sendData(char *data, int data_len) {
    static char com[133]; // = new char[data_len + 1];
    com[0] = 0x40;
    memcpy(com + 1, data, data_len);
    int ret = m_i2c.write(m_8bit_addr, com, data_len + 1, false);
    if (ret) {
      unsigned char buf[] = "send dataX error\r\n";
      m_uart.add_uart_data(buf, sizeof(buf));
    }
    // delete[] com;
    return ret;
  }

  void recover() {
    volatile int ret = 1;
    while (ret) {
      thread_sleep_for((uint32_t)1);
      m_i2c.stop();
      char buf[1];
      thread_sleep_for((uint32_t)1);
      ret = m_i2c.read(m_8bit_addr, buf, 1);
    }
  }

  // Initialize the SSD1305 display
